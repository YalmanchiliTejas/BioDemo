// End-to-end checks for the work model, evidence boundaries, and resilient storage.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs');
const out = process.env.SCREENSHOT_DIR || '/private/tmp/biodemo-ethos-review';
const base = process.env.WORKSPACE_URL || 'http://127.0.0.1:5183';
const assert = (value, message) => { if (!value) throw Error(message); };
(async () => {
  fs.mkdirSync(out, { recursive: true });
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, reducedMotion: 'reduce' });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(String(e)));
  try {
    await page.goto(`${base}/app?instant`);
    await page.locator('.studio-home h1').waitFor();
    await page.evaluate(() => document.fonts.ready);
    await page.screenshot({ path: `${out}/home-desktop.png` });
    await page.getByRole('button', { name: 'New work', exact: true }).last().click();
    await page.getByLabel('Your question or goal').fill('Review cleaning verification for Suite 2');
    await page.getByLabel('Starting context').selectOption('none');
    await page.getByRole('button', { name: 'Start work', exact: true }).click();
    await page.getByRole('heading', { name: 'Review cleaning verification for Suite 2', exact: true }).waitFor();
    assert(await page.getByText('Goal saved. No new analysis has run.').count() === 1, 'A new goal must not imply completed analysis');
    await page.getByRole('tab', { name: 'Notes', exact: true }).click();
    await page.getByLabel('Note or correction').fill('Check the approved record version before interpreting the results.');
    await page.getByRole('button', { name: 'Save note', exact: true }).click();
    await page.reload();
    await page.getByText('Check the approved record version before interpreting the results.', { exact: true }).waitFor();
    const savedUrl = page.url();
    const exportPromise = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Export work', exact: true }).click();
    const exported = await exportPromise;
    const exportData = JSON.parse(fs.readFileSync(await exported.path(), 'utf8'));
    assert(exportData.work.goal === 'Review cleaning verification for Suite 2', 'Export must preserve the actual goal');
    assert(exportData.work.notes.length === 1 && exportData.evidence.length === 0, 'A context-free draft must not acquire sample evidence in export');
    await page.getByRole('tab', { name: 'Overview', exact: true }).click();
    await page.getByRole('button', { name: 'Explore with sample context', exact: true }).click();
    await page.getByRole('heading', { name: 'Titer comparison' }).waitFor();
    await page.getByText('Goal saved. No new analysis has run.', { exact: true }).waitFor();
    await page.getByRole('tab', { name: /Notes/ }).click();
    await page.reload();
    await page.getByText('Check the approved record version before interpreting the results.', { exact: true }).waitFor();
    await page.getByText('Attached the F-2408 sample context for exploration. No new analysis has run.', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Propose next step', exact: true }).click();
    const proposal = page.getByRole('dialog');
    await proposal.getByLabel('Proposed next step').fill('Verify the approved cleaning record');
    await proposal.getByLabel('Responsible person or role').fill('QA reviewer');
    await proposal.getByLabel('Rationale and uncertainty').fill('The record version is not yet confirmed.');
    await proposal.getByLabel('Expected result or outcome measure').fill('Record ID, revision and approval timestamp are confirmed.');
    await proposal.getByLabel('Constraints and required approval').fill('Read-only review. No batch release decision.');
    await proposal.getByRole('button', { name: 'Save proposal', exact: true }).click();
    await page.getByRole('navigation', { name: 'Manufacturing OS' }).getByRole('button', { name: 'Actions', exact: true }).click();
    await page.getByRole('heading', { name: 'Verify the approved cleaning record', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Record local review', exact: true }).click();
    await page.getByLabel('Review or progress note').fill('Reviewed the task, evidence gap and access boundary.');
    await page.getByRole('button', { name: 'Save record', exact: true }).click();
    await page.getByRole('button', { name: 'Record work started', exact: true }).click();
    await page.getByLabel('Review or progress note').fill('Requested the approved revision from QA.');
    await page.getByRole('button', { name: 'Save record', exact: true }).click();
    await page.getByRole('button', { name: 'Record observed outcome', exact: true }).click();
    await page.getByLabel('Observed outcome, evidence and remaining uncertainty').fill('Revision C confirmed; technical interpretation still requires review.');
    await page.getByRole('button', { name: 'Save record', exact: true }).click();
    await page.reload();
    await page.locator('.ws-action-card > header .ws-tag').filter({ hasText: 'Outcome recorded' }).waitFor();
    await page.getByText('Review history · 4 entries', { exact: true }).click();
    await page.getByText('Revision C confirmed; technical interpretation still requires review.', { exact: true }).waitFor();
    await page.screenshot({ path: `${out}/actions-desktop.png` });
    await page.getByRole('button', { name: 'Track sample checks', exact: true }).first().click();
    await page.getByRole('heading', { name: 'Take a portable DO reading on BR-04 at the 12:00 sample', exact: true }).waitFor();
    await page.getByRole('navigation', { name: 'Manufacturing OS' }).getByRole('button', { name: /Saved work/ }).click();
    await page.getByRole('textbox', { name: 'Find saved work' }).fill('cleaning');
    assert(await page.locator('.ws-work-row').count() === 1, 'Saved work search must filter results');
    await page.getByRole('textbox', { name: 'Find saved work' }).fill('not present');
    await page.getByRole('heading', { name: 'No matching work' }).waitFor();
    await page.getByRole('button', { name: 'Clear filters' }).click();
    await page.locator('.ws-work-row').filter({ hasText: 'Understand the lower titer in F-2408' }).click();
    await page.getByRole('heading', { name: 'Titer comparison' }).waitFor();
    await page.getByRole('tab', { name: 'Evidence', exact: true }).click();
    await page.locator('.flow-evidence-full .ev').first().click();
    await page.getByRole('dialog').waitFor();
    await page.keyboard.press('Escape');
    await page.screenshot({ path: `${out}/evidence-desktop.png` });
    await page.getByRole('button', { name: 'Open scientific workspace', exact: true }).click();
    await page.getByRole('tab', { name: /Investigation/ }).waitFor();
    await page.getByRole('button', { name: 'Review plan', exact: true }).first().click();
    await page.getByRole('button', { name: 'Save simulated quality draft', exact: true }).click();
    await page.getByRole('button', { name: 'Done', exact: true }).click();
    await page.reload();
    await page.getByRole('button', { name: 'View receipt', exact: true }).first().waitFor();
    await page.keyboard.press('Control+k');
    await page.getByRole('dialog', { name: 'Search' }).waitFor();
    await page.getByPlaceholder('Find work, sources, or actions…').fill('cleaning');
    await page.getByRole('option', { name: 'Review cleaning verification for Suite 2' }).click();
    assert(new URL(page.url()).searchParams.get('work') === new URL(savedUrl).searchParams.get('work'), 'Search should resume the same saved work');
    for (const width of [320, 390, 768, 1024, 1440]) {
      await page.setViewportSize({ width, height: width < 768 ? 844 : 1100 });
      for (const view of ['', '&view=work', '&view=actions', '&view=sources']) {
        await page.goto(`${base}/app?instant${view}`);
        await page.locator('.workspace-view h1').waitFor();
        assert(!await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), `Overflow at ${width} / ${view}`);
      }
      if (width === 390) {
        await page.goto(`${base}/app?instant`);
        await page.screenshot({ path: `${out}/home-mobile.png`, fullPage: true });
        await page.getByRole('button', { name: 'Open menu', exact: true }).click();
        await page.getByRole('dialog').getByRole('button', { name: /^Saved work \d+$/ }).click();
        await page.getByRole('heading', { name: 'Saved work', exact: true }).waitFor();
      }
    }
    const recovery = await context.newPage();
    await recovery.goto(base);
    await recovery.evaluate(() => localStorage.setItem('manufacturing-os:workspace:v1', '{broken-data'));
    await recovery.goto(`${base}/app?instant`);
    await recovery.getByRole('alert').getByText(/Saved work could not be read/).waitFor();
    assert(await recovery.evaluate(() => localStorage.getItem('manufacturing-os:workspace:v1')) === '{broken-data', 'Recovery must preserve the invalid saved copy');
    await recovery.close();
    const noStorage = await browser.newContext({ viewport: { width: 1280, height: 900 } });
    await noStorage.addInitScript(() => { Storage.prototype.setItem = () => { throw new DOMException('Storage full', 'QuotaExceededError'); }; });
    const blocked = await noStorage.newPage();
    await blocked.goto(`${base}/app?instant`);
    await blocked.getByRole('alert').getByText(/Browser storage is unavailable or full/).waitFor();
    await blocked.getByRole('button', { name: 'New work', exact: true }).last().click();
    await blocked.getByLabel('Your question or goal').fill('Keep work usable without storage');
    await blocked.getByRole('button', { name: 'Start work', exact: true }).click();
    await blocked.getByRole('heading', { name: 'Keep work usable without storage', exact: true }).waitFor();
    await noStorage.close();
    assert(errors.length === 0, errors.join('\n'));
    console.log(JSON.stringify({ passed: true, screenshots: out, browserErrors: errors.length }));
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exit(1); });
