/* Local browser contract. Uses explicit fixtures; never sends requests to real APIs.
 * PLAYWRIGHT_MODULE=/path/to/playwright node scripts/check_workspace_navigation.cjs [preview URL]
 */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.argv[2] || 'http://127.0.0.1:5180';
const output = process.env.WORKSPACE_CHECK_ARTIFACTS || '/private/tmp/biodemo-workspace-redesign';
const org = { id: 'preview-org', name: 'Preview Biologics', roles: ['admin'], site_ids: [], onboarding_complete: true };
const account = { actor_id: 'preview-user', organizations: [org, { ...org, id: 'other-preview', name: 'Preview Research' }], can_create_organization: true };
const summary = { verified_package: false, review_groups: 2, open_issues: 1, unconfirmed_layouts: 0 };
let membershipRequests = [];
let memberRole = 'admin';
let failRuns = false;
const connection = { connector_id: 'preview-lims', family: 'LIMS', transport: 'rest', site_id: 'SITE-1', owner: 'preview-user', vendor: '', version: '', options: { poll_seconds: 0 }, enabled: true, write_operations: [], last_sync: '2026-10-31T12:00:00Z' };
const members = [{ actor_id: 'preview-colleague', email: 'colleague@example.test', role: 'operator', site_id: 'SITE-1' }];
(async () => {
  fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch();
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1050 } });
    const page = await context.newPage();
    const exceptions = [];
    page.on('pageerror', error => exceptions.push(error.message));
    await page.addInitScript(() => { localStorage.setItem('sievance.organization:preview-user', 'preview-org'); if (!localStorage.getItem('cmo.reviewer')) localStorage.setItem('cmo.reviewer', 'Preview Reviewer'); });
    await page.route('**/*', async route => {
      const request = route.request();
      const url = new URL(request.url());
      if (!url.pathname.startsWith('/v1/') && !url.pathname.startsWith('/api/cmo-ingestion/')) return route.continue();
      const headers = { 'Access-Control-Allow-Origin': '*', 'Access-Control-Allow-Headers': '*', 'Access-Control-Allow-Methods': 'GET,POST,OPTIONS', 'Content-Type': 'application/json' };
      if (request.method() === 'OPTIONS') return route.fulfill({ status: 204, headers, body: '' });
      let data;
      if (url.pathname === '/v1/account') data = { ...account, organizations: [{ ...org, roles: [memberRole] }, account.organizations[1]] };
      else if (url.pathname === '/v1/me') data = { tenant_id: org.id, actor_id: 'preview-user', roles: [memberRole], site_ids: [], auth_mode: 'development' };
      else if (url.pathname === '/v1/connectors') data = { items: [connection] };
      else if (url.pathname === '/v1/connectors/catalog') data = { families: [{ system: 'LIMS', record_type: 'lab result', template: { template_id: 'preview', version: '1', fields: [] } }, { system: 'MES', record_type: 'batch record', template: { template_id: 'preview-mes', version: '1', fields: [] } }], transports: [{ transport: 'rest', available: true }] };
      else if (url.pathname === '/api/cmo-ingestion/runs') {
        if (failRuns) return route.fulfill({ status: 500, headers, body: JSON.stringify({ detail: 'Preview delivery service unavailable' }) });
        data = { runs: [{ id: 'preview-run', cmo: 'Preview partner', delivery_name: 'October delivery', status: 'complete', documents: 3, started_at: '2026-10-31T12:00:00Z', summary }] };
      } else if (url.pathname === '/v1/organization/members') {
        if (request.method() === 'POST') membershipRequests.push(request.postDataJSON());
        data = { items: members };
      } else if (url.pathname === '/api/cmo-ingestion/catalog') data = { packages: [], cmos: [], customer_availability: {}, hosted_inference_approved: false, storage: { records: 'fixture', originals: 'fixture' } };
      else if (url.pathname === '/api/cmo-ingestion/vocabulary') data = { parameters: [] };
      else return route.fulfill({ status: 404, headers, body: JSON.stringify({ detail: `Unmocked preview path: ${url.pathname}` }) });
      await route.fulfill({ status: 200, headers, body: JSON.stringify(data) });
    });
    const check = name => console.log(`PASS ${name}`);
    const noOverflow = async () => assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.goto(`${base}/dashboard/`);
    await page.getByRole('link', { name: 'October delivery Preview partner' }).waitFor();
    assert.equal(await page.getByRole('dialog', { name: 'Workspace guide' }).count(), 0);
    check('dashboard loads real API-shaped counts and recent work without an automatic tutorial');
    await page.getByLabel('Filter navigation', { exact: true }).fill('profile');
    await page.getByRole('navigation', { name: 'Primary', exact: true }).getByRole('link', { name: 'My profile', exact: true }).waitFor();
    await page.getByLabel('Filter navigation', { exact: true }).fill('');
    await page.getByRole('button', { name: 'Collapse navigation', exact: true }).click();
    await page.reload();
    await page.getByRole('button', { name: 'Expand navigation', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Expand navigation', exact: true }).click();
    check('navigation searches across sections and remembers collapsed preference');
    await page.screenshot({ path: `${output}/dashboard-desktop.png`, fullPage: true });
    for (const width of [900, 1024]) {
      await page.setViewportSize({ width, height: 1000 });
      await noOverflow();
      assert(await page.locator('.delivery-table').evaluate(node => node.getBoundingClientRect().right <= node.closest('.workspace-panel').getBoundingClientRect().right));
    }
    await page.setViewportSize({ width: 1440, height: 1050 });
    check('tablet widths keep delivery columns within their panel');
    await page.getByRole('button', { name: 'Open workspace guide', exact: true }).click();
    const guide = page.getByRole('dialog', { name: 'Workspace guide' });
    await guide.getByRole('button', { name: 'Connect your data' }).click();
    await page.locator('[data-guide="connections"].guide-target').waitFor();
    assert.equal(await guide.locator('button:disabled').count(), 0);
    await page.screenshot({ path: `${output}/guide-desktop.png`, fullPage: true });
    await page.getByRole('link', { name: 'Connections', exact: true }).first().click();
    await page.getByRole('heading', { name: 'Data connections', exact: true }).waitFor();
    assert(await guide.isVisible());
    await guide.getByRole('button', { name: 'Got it' }).click();
    await guide.getByText('1 of 6 topics explored', { exact: false }).waitFor();
    await page.keyboard.press('Escape');
    assert.equal(await guide.count(), 0);
    check('optional guide follows controls, allows free navigation, records topics, and closes with Escape');
    await page.getByRole('searchbox', { name: 'Search data sources' }).fill('nonexistent');
    await page.getByText('No sources match your search.', { exact: false }).waitFor();
    await page.getByRole('searchbox', { name: 'Search data sources' }).fill('LIMS');
    assert.equal(await page.locator('.connector-choice').count(), 1);
    check('source onboarding catalog filters and has a clear empty state');
    await page.goto(`${base}/settings/organization/`);
    await page.getByText('colleague@example.test', { exact: true }).waitFor();
    await page.getByText('Grant team access', { exact: true }).click();
    await page.getByLabel('Account email', { exact: true }).fill('new-colleague@example.test');
    await page.getByLabel('Site scope', { exact: true }).fill('SITE-1');
    await page.getByRole('button', { name: 'Grant access', exact: true }).click();
    await page.getByRole('status').filter({ hasText: 'Access granted.' }).waitFor();
    assert.deepEqual(membershipRequests[0], { email: 'new-colleague@example.test', role: 'operator', site_id: 'SITE-1' });
    await page.getByRole('button', { name: 'Revoke role', exact: true }).click();
    assert.equal(membershipRequests.length, 1);
    await page.getByRole('button', { name: 'Cancel', exact: true }).click();
    assert.equal(membershipRequests.length, 1);
    check('team grant keeps role/site payload; opening or cancelling revocation changes no access');
    await page.locator('#main').evaluate(node => { node.scrollTop = 0; });
    await page.screenshot({ path: `${output}/organization-desktop.png`, fullPage: true });
    await page.getByRole('button', { name: 'Switch organization', exact: true }).click();
    await page.getByRole('button', { name: /Preview Research/ }).waitFor();
    await page.keyboard.press('Escape');
    assert.equal(await page.getByLabel('Organization switcher', { exact: true }).count(), 0);
    check('organization switcher lists memberships and dismisses with Escape');
    await page.goto(`${base}/settings/profile/`);
    await page.getByRole('heading', { name: 'My profile', exact: true }).waitFor();
    await page.getByLabel('Display name', { exact: true }).fill('Updated Preview');
    await page.getByRole('button', { name: 'Save changes', exact: true }).click();
    await page.getByRole('status').filter({ hasText: 'display name has been saved' }).waitFor();
    await page.getByRole('button', { name: 'Open account menu' }).click();
    await page.locator('.popover-account strong').filter({ hasText: 'Updated Preview' }).waitFor();
    await page.keyboard.press('Escape');
    check('profile edits persist and account menu reflects the local display name');
    await page.locator('#main').evaluate(node => { node.scrollTop = 0; });
    await page.screenshot({ path: `${output}/profile-desktop.png`, fullPage: true });
    memberRole = 'operator';
    await page.goto(`${base}/settings/organization/`);
    await page.getByText('Only an organization administrator', { exact: false }).waitFor();
    assert.equal(await page.getByText('Grant team access', { exact: true }).count(), 0);
    check('non-administrators see their scope without team mutation controls');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto(`${base}/dashboard/`);
    await page.getByRole('link', { name: 'October delivery Preview partner' }).waitFor();
    await noOverflow();
    await page.getByRole('button', { name: 'Open workspace guide', exact: true }).click();
    await page.getByRole('button', { name: 'Open navigation', exact: true }).click();
    assert.equal(await guide.count(), 0);
    await page.getByRole('dialog', { name: 'Workspace navigation' }).waitFor();
    await page.keyboard.press('Shift+Tab');
    assert(await page.locator('#workspace-navigation').evaluate(node => node.contains(document.activeElement)));
    await page.keyboard.press('Escape');
    assert.equal(await page.getByRole('dialog', { name: 'Workspace navigation' }).count(), 0);
    check('mobile navigation opens, traps focus, closes with Escape, and has no page overflow');
    await page.getByRole('button', { name: 'Open workspace guide', exact: true }).click();
    await guide.getByText('1 of 6 topics explored', { exact: false }).waitFor();
    await noOverflow();
    await page.screenshot({ path: `${output}/guide-mobile.png`, fullPage: true });
    await page.keyboard.press('Escape');
    await page.screenshot({ path: `${output}/dashboard-mobile.png`, fullPage: true });
    failRuns = true;
    await page.reload();
    await page.getByRole('alert').filter({ hasText: 'Preview delivery service unavailable' }).waitFor();
    assert(await page.getByText('Unavailable', { exact: true }).count() > 0);
    failRuns = false;
    await page.getByRole('button', { name: 'Try again', exact: true }).click();
    await page.getByRole('link', { name: 'October delivery Preview partner' }).waitFor();
    check('API failures stay explicit and retry restores dashboard data');
    await page.goto(`${base}/onboarding/start/`);
    await page.getByRole('heading', { name: 'Bring your context along.' }).waitFor();
    await noOverflow();
    await page.screenshot({ path: `${output}/onboarding-mobile.png`, fullPage: true });
    check('standalone onboarding remains skippable and fits a phone viewport');
    assert.deepEqual(exceptions, []);
    check('no browser runtime exceptions');
    console.log(`Screenshots: ${output}`);
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
