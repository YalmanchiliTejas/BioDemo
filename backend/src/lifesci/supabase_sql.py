"""Render the Supabase SQL-editor migrations from the schema that ``db-migrate`` applies.

``python -m src.lifesci supabase-sql`` rewrites ``deploy/supabase/migrations``;
a test fails if the checked-in files differ from this output.
"""
from __future__ import annotations

from pathlib import Path

from .cmo_schema import CMO_PG_DDL, CMO_PG_POLICIES, TABLES, cmo_grants
from .store import _PG_DDL, _PG_RLS, _PG_UPGRADE, platform_grants

ROLE = "lifesci_app"
PLATFORM_TABLES = ("aggregates", "aggregate_revisions", "audit", "outbox", "inbox", "leases", "edges", "blobs")
MIGRATIONS = Path(__file__).resolve().parents[2] / "deploy" / "supabase" / "migrations"

_HEADER = """-- GENERATED by `python -m src.lifesci supabase-sql` from {source}.
-- Do not edit by hand. Idempotent: safe to run again, and upgrades databases
-- created by earlier versions of this file without losing records.
"""


def _close_data_api(tables: list[str], sequences: list[str]) -> str:
    # Browsers never query these tables; Supabase's anon/authenticated roles get nothing.
    return f"""
DO $$ DECLARE r text; BEGIN
  FOREACH r IN ARRAY ARRAY['anon','authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
      EXECUTE format('REVOKE ALL ON {", ".join(tables)} FROM %I', r);
      {"EXECUTE format('REVOKE ALL ON SEQUENCE " + ", ".join(sequences) + " FROM %I', r);" if sequences else ""}
    END IF;
  END LOOP;
END $$;
"""


def platform_sql() -> str:
    return (_HEADER.format(source="src/lifesci/store.py") + """--
-- Life-sciences platform record store. Run as `postgres` in the Supabase SQL
-- editor. BEFORE RUNNING, replace REPLACE_WITH_APP_PASSWORD in section 4 with a
-- new password (16+ characters) for the backend's database login, and put the
-- same password in LIFESCI_DATABASE_URL. Do not commit the edited copy.
--
-- A record's content is stored once, in its immutable revision; `aggregates`
-- only points at the current revision. Audit and revisions are append-only.

-- 1. Tables -------------------------------------------------------------------
""" + _PG_DDL.strip() + """

-- 2. Upgrade databases created before normalization ---------------------------
""" + _PG_UPGRADE.strip() + """

-- 3. Tenant row-level security and append-only history ------------------------
""" + _PG_RLS.strip() + f"""

-- 4. Runtime role (non-owner, no BYPASSRLS) -------------------------------------
DO $$ DECLARE pw text := 'REPLACE_WITH_APP_PASSWORD'; BEGIN
  IF pw = 'REPLACE' || '_WITH_APP_PASSWORD' THEN RAISE EXCEPTION 'edit the script: set the {ROLE} password first'; END IF;
  IF length(pw) < 16 THEN RAISE EXCEPTION 'app password must be at least 16 characters'; END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '{ROLE}') THEN
    EXECUTE format('ALTER ROLE {ROLE} WITH LOGIN PASSWORD %L', pw);
  ELSE
    EXECUTE format('CREATE ROLE {ROLE} WITH LOGIN PASSWORD %L NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS', pw);
  END IF;
END $$;
""" + "".join(s + ";\n" for s in platform_grants(ROLE)) + """
-- 5. Close the Supabase Data API ----------------------------------------------""" +
            _close_data_api(list(PLATFORM_TABLES), ["audit_seq_seq", "outbox_seq_seq"]))


def cmo_sql() -> str:
    return (_HEADER.format(source="src/lifesci/cmo_schema.py") + f"""--
-- CMO delivery verification records, normalized: each fact has one home row,
-- derived values are computed when read, and decisions are append-only receipts
-- in the platform `audit` table. Run after 0002_lifesci_platform.sql (it uses
-- that file's `audit` table and `{ROLE}` role).

-- 1. Tables and append-only decisions -------------------------------------------
""" + CMO_PG_DDL.strip() + """

-- 2. Tenant row-level security --------------------------------------------------
""" + CMO_PG_POLICIES.strip() + """

-- 3. Runtime role: insert-only except the columns the application updates -------
""" + "".join(s + ";\n" for s in cmo_grants(ROLE)) + """
-- 4. Close the Supabase Data API ----------------------------------------------""" +
            _close_data_api(list(TABLES), []))


def render() -> dict[str, str]:
    return {"0002_lifesci_platform.sql": platform_sql(), "0003_cmo_records.sql": cmo_sql()}


def write(folder: Path = MIGRATIONS) -> list[Path]:
    folder.mkdir(parents=True, exist_ok=True)
    written = []
    for name, text in render().items():
        (folder / name).write_text(text)
        written.append(folder / name)
    return written
